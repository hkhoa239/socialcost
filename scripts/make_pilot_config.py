#!/usr/bin/env python3
"""Write configs/dataset/pilot_v1.yaml and the experiment split from the pair lists.

Jobs (one episode each, warm-up episode discarded, bodies-only Nav2):
  map_empty pairs:   4 families x body sets bA bB bC bD bH x ON/OFF
  reception pairs:   4 families x body set bA x ON/OFF          (unseen world)
  group-walk variants, single pedestrians, empty world, original conversation / queue / group walk

Splits (whole pairs, both conditions together):
  train: map_empty bA bB + group-walk bA + controls     val: map_empty bC
  test_A (in-distribution): map_empty bD                  test_B (unseen world): reception bA
  test_C (unseen appearance): map_empty bH + group-walk bH
  test_D (paired semantic challenge): every held-out pair, i.e. the pairs in test_A, test_B, test_C
"""

from __future__ import annotations

import json
import os

import yaml

PKG = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
C = os.path.join(PKG, "configs", "dataset")
SEEDS = {"bA": 21, "bB": 22, "bC": 23, "bD": 24, "bH": 25}


def main() -> int:
    jobs, seed = [], 100
    for world in ("map_empty", "reception"):
        for p in json.load(open(os.path.join(C, f"pairs_{world}.json"))):
            if world == "reception" and p["body_set"] != "bA":
                continue
            for cond in ("on", "off"):
                jobs.append({"scenario": p[cond], "seed": SEEDS[p["body_set"]] + (10 if world != "map_empty" else 0), "world": world,
                             "pair_id": p["pair_id"], "condition": cond, "family": p["family"], "body_set": p["body_set"],
                             "observability": p["observability"], "held_out_bodies": p["held_out_bodies"], "placement_offset": p["placement_offset"],
                             # queue members re-slot themselves: OFF starts where the recorded ON members stood
                             **({"derive_from": p["on"]} if p["family"] == "queue" and cond == "off" else {})})
    for v in ("slow", "fast", "diagonal"):
        for bs in ("bA", "bH"):
            jobs.append({"scenario": f"socialcost_gw_{v}_{bs}", "seed": SEEDS[bs] + 40, "world": "map_empty", "family": "group_walk", "body_set": bs,
                         "pair_id": f"gw_{v}_{bs}", "condition": "", "held_out_bodies": bs == "bH"})
    for scen, fam in (("socialcost_verify_single", "single"), ("socialcost_verify_empty", "empty"), ("socialcost_conversation", "conversation_route"),
                      ("socialcost_queue", "queue_route"), ("socialcost_group_walk", "group_walk")):
        seed += 1
        jobs.append({"scenario": scen, "seed": seed, "world": "map_empty", "family": fam, "body_set": "bA", "pair_id": f"ctl_{scen}", "condition": ""})
    cfg = {"name": "socialcost_pilot_v1", "output": "/opt/arena_ws/data/socialcost/datasets/pilot_v1", "world": "map_empty", "sensors": "turtlebot_oakd",
           "sample_hz": 5.0, "duration_s": 20.0, "warmup_s": 8.0, "fresh_margin_s": 0.5, "warmup_episode": True, "require_cost": False,
           "label": {"overlay": "arena_robots/arena_robots/config/nav2/overlays/social_cost_layer.yaml", "costmap": "local_costmap", "size_m": 10.0, "resolution": 0.05},
           "live_costmap": False, "launch_args": [], "jobs": jobs,
           "splits": {"test": {"body_sets": ["bD", "bH"], "worlds": ["reception"]}, "val": {"body_sets": ["bC"]}}}
    with open(os.path.join(C, "pilot_v1.yaml"), "w") as f:
        f.write("# SOCIALCOST pilot_v1 (generated by make_pilot_config.py). Bodies-only Nav2, warm-up episode discarded.\n")
        yaml.safe_dump(cfg, f, sort_keys=False)
    print(f"{len(jobs)} jobs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
