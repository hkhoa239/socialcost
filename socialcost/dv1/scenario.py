"""Compile a dataset_v1 manifest episode into an arena-scenario/2 directory with humansim behaviour trees."""

from __future__ import annotations

import json
import os
import shutil

import yaml

from .geometry import WORLDS_DIR

HEADER = "# SOCIALCOST dataset_v1 episode {eid} ({family}, {cond}), generated by scripts/dv1_make_scenarios.py from the frozen manifest.\n"


def scenario_name(eid: str) -> str:
    return f"scv1_{eid}"


def _dur(t: float) -> dict:
    return {"mean": float(round(t, 3)), "std": 0.0}


def compile_steps(steps: list[dict]) -> dict:
    out = {}
    for i, st in enumerate(steps):
        key = f"s{i:02d}"
        if "wait" in st:
            if st["wait"] <= 0:
                continue
            out[key] = {"duration": _dur(st["wait"])}
        elif "goto" in st:
            x, y, th = st["goto"]
            out[key] = {"kind": "go_to", "target_pose": {"x": float(round(x, 3)), "y": float(round(y, 3)), "theta": float(round(th, 4))}}
        elif "interact" in st:
            out[key] = {"interaction": st["interact"], "attention": {"gaze": "partner"}, "duration": _dur(st["duration"]), "patience": _dur(2000.0)}
        elif "halt" in st:
            out[key] = {"attention": {"halt": {"azimuth": st["halt"]["azimuth"], "elevation": st["halt"]["elevation"]}}, "duration": _dur(st["duration"])}
        elif "queue" in st:
            # humansim resolves QUEUE_USE targets by object type (the pilot_v1 queues used `desk`); one desk per scene
            out[key] = {"target": "desk", "interaction": "QUEUE_USE", "duration": _dur(st["service"]), "patience": _dur(2000.0)}
        elif "group_form" in st:
            out[key] = {"interaction": "GROUP_WALK"}
        elif "group_join" in st:
            out[key] = {"interaction": "GROUP_WALK", "duration": _dur(1000.0)}
        else:
            raise ValueError(f"unknown step {st}")
    if not out:
        out["s00"] = {"duration": _dur(1000.0)}
    return out


SEEK_STAGGER_S = 1.0  # compiler v1.1: see stagger_seek


def stagger_seek(steps: list[dict], name: str) -> list[dict]:
    """Two participants that arrive by go_to and seek the same symmetric interaction at once can each open their own
    one-member FORMING interaction and never merge (humansim symmetric seek; seen in 3 of 15 approach-and-stop pairs).
    Participant k waits k * SEEK_STAGGER_S after arriving, so the first opens the interaction and the others join it."""
    try:
        k = int(name.rsplit("_", 1)[1])
    except (IndexError, ValueError):
        return steps
    out = []
    for i, st in enumerate(steps):
        if "interact" in st and i > 0 and "goto" in steps[i - 1] and k > 0:
            out.append({"wait": SEEK_STAGGER_S * k})
        out.append(st)
    return out


def agent_file(name: str, behavior: dict, agent_type: str, speed: float | None) -> dict:
    doc = {"name": name, "mode": "behavior_tree", "extends": agent_type, "initial_sequence": "main"}
    if speed:
        doc["desired_velocity"] = {"mean": float(speed), "std": 0.0, "clip_low": 0.2, "clip_high": 2.0}
    loop = behavior.get("loop", False)
    steps = stagger_seek(behavior["steps"], name) if name.startswith("scv1_participant_") else behavior["steps"]
    doc["sequences"] = {"main": {"steps": compile_steps(steps), "then": "main" if loop else "rest"},
                        "rest": {"steps": {"hold": {"duration": _dur(1000.0)}}, "then": "rest"}}
    return doc


def write_episode(ep: dict, overwrite: bool = True) -> str:
    world = ep["world"]
    d = os.path.join(WORLDS_DIR, world, "scenarios", scenario_name(ep["episode_id"]))
    if os.path.isdir(d):
        if not overwrite:
            return d
        shutil.rmtree(d)
    os.makedirs(d)
    cond = ep["condition"]
    humans = []
    for h in ep["humans"]:
        fname = f"{h['name']}.yaml"
        beh = h["behavior"][cond]
        yaml.safe_dump(agent_file(f"scv1_{h['name']}", beh, h["agent_type"][cond], h.get("speed")), open(os.path.join(d, fname), "w"), sort_keys=False)
        humans.append({"name": h["name"], "model": h["body"], "pose": [float(v) for v in h["spawn"]], "agent": {"agent_type": f"./{fname}"}})
    doc = {"format": "arena-scenario/2"}
    if ep["objects"]:
        doc["objects"] = json.loads(json.dumps(ep["objects"]))
    if humans:
        doc["humans"] = humans
    r = ep["robot"]
    doc["robots"] = [{"start": [float(v) for v in r["start"]], "phases": [{"goto": [float(v) for v in r["goal"]]}]}]
    with open(os.path.join(d, "scenario.yaml"), "w") as f:
        f.write(HEADER.format(eid=ep["episode_id"], family=ep["family"], cond=cond))
        yaml.safe_dump(doc, f, sort_keys=False)
    return d
